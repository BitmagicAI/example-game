// Builds the pick-your-roller screen into tor/PickScreenMarkup.ts, which the game puts on the page when it boots (tor/CharacterSelect.ts).
//   node tools/pick-screen/build.mjs            (re)generate the module; idempotent
//   node tools/pick-screen/build.mjs --check    exit 1 when the module is not exactly what this tool would write
//
// The screen is built from: tools/pick-screen/overlay.src.html (markup, CSS, script), tor/roster.ts (who, names, blurbs), tools/pick-screen/portraits/<id>.webp,
// tools/pick-screen/fonts/lilita-one.woff2, and the asset URLs in world.json (what the screen starts downloading while the game loads). Every input is baked in,
// so RE-RUN THIS after a portrait, roster, overlay or stage URL change. `--check` says when that is due, and the game warns on the console when the URLs baked into the
// screen differ from the ones in world.json (tor/CharacterSelect.ts).
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.resolve(here, '..', '..');
const target = path.join(root, 'tor', 'PickScreenMarkup.ts');
const check = process.argv.includes('--check');

// Node strips the types from the game's own .ts data files, so the tool reads the very same roster the game does
const { ROSTER } = await import(pathToFileURL(path.join(root, 'tor', 'roster.ts')).href);
const world = JSON.parse(fs.readFileSync(path.join(root, 'world.json'), 'utf8'));

const src = fs.readFileSync(path.join(here, 'overlay.src.html'), 'utf8');
const pick = (name) => { const m = src.match(new RegExp(`<!-- tor-rs:${name}:begin[\\s\\S]*?<!-- tor-rs:${name}:end -->`)); if (!m) throw new Error(`overlay.src.html has no tor-rs:${name} block`); return m[0]; };
const fail = (m) => { console.error('ERROR: ' + m); process.exit(1); };

// the assets the screen prefetches: by NAME (the game asks for stages and animals by name), sized from world.json (the real size replaces it when the response arrives)
// a game-asset: URL is baked as the engine resolves it (engine/runtime/hosting.ts resolveGameAssetUrl): the screen's script fetches it as it is, and the game looks the bytes up by that URL
const resolved = (url) => (url.startsWith('game-asset:') ? `./assets/${url.slice('game-asset:'.length).replace(/^\/+/, '')}` : url);
const asset = (name) => { const a = world.assets.find((x) => x.name === name || x.id === name); if (!a?.url) fail(`world.json has no asset "${name}"`); return { u: resolved(a.url), w: a.size || 300000 }; };
const urls = { menuStage: asset(ROSTER.menuStage), firstStage: asset(ROSTER.firstStage) };
const cfg = { saveKey: 'trickorroll:v1', characters: ROSTER.characters.map(({ id, name, blurb, tint }) => ({ id, name, blurb, tint })), urls };

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const b64 = (file) => fs.readFileSync(file).toString('base64');
const fontFile = path.join(here, 'fonts/lilita-one.woff2');
if (!fs.existsSync(fontFile)) fail('missing tools/pick-screen/fonts/lilita-one.woff2');
const font = `@font-face { font-family: 'TOR Lilita'; font-style: normal; font-weight: 400; font-display: block; src: url(data:font/woff2;base64,${b64(fontFile)}) format('woff2'); }`;
const cards = ROSTER.characters.map((c) => {
    const f = path.join(here, 'portraits', `${c.id}.webp`);
    if (!fs.existsSync(f)) fail(`missing portrait ${path.relative(root, f)} (a 420x560 WebP of the animal)`);
    return `        <button class="tor-card" type="button" role="radio" aria-checked="false" data-id="${esc(c.id)}" style="--tint:${esc(c.tint)}"><img alt="" width="420" height="560" decoding="async" draggable="false" src="data:image/webp;base64,${b64(f)}"><span class="tor-name">${esc(c.name)}</span><i class="tor-ok"></i></button>`;
}).join('\n');
const json = JSON.stringify(cfg).replace(/</g, '\\u003c').replace(/>/g, '\\u003e').replace(/&/g, '\\u0026').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const fill = (block) => block.replace('%%FONT%%', () => font).replace('%%CARDS%%', () => cards).replace('%%CONFIG%%', () => json);
const headBlock = fill(pick('head')), bodyBlock = fill(pick('body'));
if (/%%[A-Z]+%%/.test(headBlock + bodyBlock)) fail('an unfilled %%placeholder%% is left in the overlay');
{   // catch the cheap stylesheet mistakes here rather than in the browser
    const css = headBlock.replace(/url\(data:[^)]*\)/g, 'url()');
    if ((css.match(/{/g) || []).length !== (css.match(/}/g) || []).length) fail('the overlay stylesheet has unbalanced braces');
}

const module = `// Generated by tools/pick-screen/build.mjs from tools/pick-screen/overlay.src.html: edit THAT file and run the tool, not this one.
/** The pick screen's styles (with the game's font): they go into <head>. */
export const PICK_SCREEN_HEAD = ${JSON.stringify(headBlock)};
/** The pick screen's markup and scripts: they go into <body>. */
export const PICK_SCREEN_BODY = ${JSON.stringify(bodyBlock)};
`;
const before = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
if (check) {
    if (module === before) { console.log(`ok: ${path.relative(root, target)} is current`); process.exit(0); }
    console.error(`STALE: ${path.relative(root, target)} differs from what tools/pick-screen/build.mjs writes. Run: node tools/pick-screen/build.mjs`);
    process.exit(1);
}
if (module !== before) fs.writeFileSync(target, module);
const kb = (n) => (n / 1024).toFixed(1);
console.log(`${module === before ? 'unchanged' : 'wrote'} ${path.relative(root, target)}: pick screen = ${kb(headBlock.length + bodyBlock.length)} KB of markup (font + ${ROSTER.characters.length} portraits inline)`);
console.log(`  the screen downloads: ${ROSTER.menuStage} ${kb(urls.menuStage.w)} KB when the engine starts, then (once the game is ready) ${ROSTER.firstStage} ${kb(urls.firstStage.w)} KB`);
